import sympy as sp

x = sp.symbols('x')
pi = sp.pi

print("1.1)", sp.integrate((x**2 + 1)**2, (x, 0, 1)))
print("1.2)", sp.integrate(sp.cos(x)**2, (x, 0, pi/2)))
print("1.3)", sp.integrate((3*x**4 + 3*x**2 + 1)/(1 + x**2), (x, -pi/4, 0)))
print("1.4)", sp.integrate(sp.exp(x/3), (x, 0, 3)))
print("1.5)", sp.integrate(sp.sqrt(sp.sin(x))*sp.cos(x), (x, 0, pi/2)))
print("1.6)", sp.integrate(1/(sp.sqrt(x) - 1), (x, 4, 9)))
print("1.7)", sp.integrate(1/(sp.exp(x) + 1), (x, 0, 1)))
print("1.8)", sp.integrate(x*sp.exp(-x), (x, 0, 1)))
print("1.9)", sp.integrate(x*sp.cos(3*x), (x, 0, pi/6)))
print("1.10)", sp.integrate(sp.log(x)/x**3, (x, 1, sp.E)))
print("1.11)", sp.integrate(sp.log(x)**3, (x, 1, sp.E)))
print("1.12)", sp.integrate(1/(2*sp.cos(x) + 3), (x, 0, pi/2)))
print("1.13)", sp.integrate(1/(x + x**2), (x, 1, 3)))
print("1.14)", sp.integrate(1/(x**2 + 2*x + 2), (x, -1, 1)))
print("1.15)", sp.integrate(1/(x + x**3), (x, 1, 2)))
print("1.16)", sp.integrate(x**3/(x**2 - 3*x + 2), (x, 0, sp.Rational(1,2))))
print("1.17)", sp.integrate(sp.sqrt(16 - x**2), (x, 0, 4)))
print("1.18)", sp.integrate(sp.cos(x)/sp.sin(x)**3, (x, pi/6, pi/2)))

print("\n")

