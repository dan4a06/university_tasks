print("1.8)", sp.Integral(x/(x**2 + 3*x + 2), (x, 0, 1)).doit())
print("1.9)", sp.Integral(1/(x*(x + 1)**2), (x, 1, 2)).doit())
print("1.10)", sp.Integral(sp.sin(5*x)*sp.cos(3*x), (x, 0, pi/4)).doit())
print("1.11)", sp.Integral(sp.cos(x)/(6 - 5*sp.sin(x) + sp.sin(x)**2), (x, 0, pi/2)).doit())
print("1.12)", sp.Integral(x**2*sp.sqrt(9 - x**2), (x, 0, 3)).doit())

